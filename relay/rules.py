"""PS5 rules gate for Muse-generated native source.

Each rule encodes something verified on the owner's PS5 (FW 12.40) or required
by the native kit. Violations fail the build before compiling, with a fix hint;
the job then returns to Muse for an automatic fix (up to the attempt limit), so
known-bad code never reaches the console. The full guide Muse reads is
relay/build/PS5-RULES.md.
"""
from __future__ import annotations

import re

# (pattern on comment/string-stripped code, message with the fix)
RULES = [
    (r"\b(?:socket|connect|bind|listen|accept|getaddrinfo|gethostbyname)\s*\(",
     "networking is not available to generated apps (the PS5 title sandbox also blocks BSD sockets)"),
    (r"\b(?:fread|fgets|getline|fscanf)\s*\(|\bstd::ifstream\b|\bstd::fstream\b",
     "stdio/iostream file reads fail at end-of-file on the PS5 title filesystem; "
     "use hui::save::read_file / write_file from core/save_file.hpp"),
    (r"(?<![\w:])(?:std::)?(?:exit|_exit|_Exit|abort|quick_exit)\s*\(",
     "end the app with hui::sys::quit() from platform/ps5/system.hpp, never exit()/abort()"),
    (r"\b(?:system|popen|fork|vfork|execv|execl|execvp|execlp|dlopen)\s*\(",
     "processes and dynamic loading are not available in a PS5 title"),
    (r"\bthrow\b|\btry\s*\{|\bcatch\s*\(|\btypeid\s*\(|\bdynamic_cast\s*<",
     "the kit compiles C++20 without exceptions or RTTI: no throw/try/catch/typeid/dynamic_cast"),
    (r"#\s*include\s*[<\"](?:SDL|GL/|GLES|vulkan|windows\.h|unistd_ps4)",
     "use only the kit's headers (gfx/, ui/, core/, audio/, platform/ps5/) and the C++ standard library"),
]
REQUIRED = [
    (r"\bquit\s*\(", "main.cpp must end through hui::sys::quit() (Circle should exit the app)"),
]


def strip_code(text: str) -> str:
    """Remove comments and the contents of string/char literals, keep line breaks."""
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if text.startswith("//", i):
            j = text.find("\n", i)
            i = n if j < 0 else j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            chunk = text[i:n if j < 0 else j + 2]
            out.append("\n" * chunk.count("\n"))
            i = n if j < 0 else j + 2
        elif c == "R" and text.startswith('R"', i):
            m = re.match(r'R"([^(\s]{0,16})\(', text[i:])
            if m:
                end = text.find(")" + m.group(1) + '"', i)
                chunk = text[i:n if end < 0 else end + len(m.group(1)) + 2]
                out.append('""' + "\n" * chunk.count("\n"))
                i = n if end < 0 else end + len(m.group(1)) + 2
            else:
                out.append(c)
                i += 1
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            out.append(c + c)
            i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


def check(files: dict[str, str]) -> list[str]:
    """Return human-readable violations (empty when the source passes)."""
    problems = []
    for name in sorted(files):
        if name == "include/muse_images.hpp":
            continue  # generated by the relay
        code = strip_code(files[name])
        for pattern, message in RULES:
            match = re.search(pattern, code)
            if match:
                line = code.count("\n", 0, match.start()) + 1
                problems.append(f"{name}:{line}: {message} (found '{match.group(0).strip()}')")
    main = strip_code(files.get("main.cpp", ""))
    for pattern, message in REQUIRED:
        if not re.search(pattern, main):
            problems.append(f"main.cpp: {message}")
    return problems
